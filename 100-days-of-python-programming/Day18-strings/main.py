# strings in Python
# single quotes
a = 'Hello'
print(a)

# double quotes
a = "Hello"
print(a)

# triple quotes(multiline string)
a = '''Hello,
I am Azka'''
print(a)

# use of single and double quotes together
# a= 'It's raining outside'(Syntax error)
a = "It's raining outside" 
print(a)

a = str("Hello") # str does nothing useful here as Hello is already a string
print(a)