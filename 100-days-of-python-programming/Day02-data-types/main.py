# int
print(8) # positive integer
print(-5) # negative integer
print(10**100) # large integer

# float
print(8.9)
print(1.8e307) # large finite float
print(1e308) # very large finite float(near float limit)
print(1e309) # infinity (overflow)
print(1.8e308) # infinity (overflow)
print(1.9e308) # infinity (overflow)

# bool
print(True)
print(False)

# str
print("Hello World") # double string quotes
print('Hello World') # single string quotes
print("""Hello World""") # triple double quotes
print('''Hello World''') # triple single quotes

# complex
print(1+4j)

# list
print([1,2,3,4])

# tuple
print((1,2,3,4))

# set
print({1,2,3})

# dict
print({"Name":"Azka","Age":20,"Gender":"Female"})